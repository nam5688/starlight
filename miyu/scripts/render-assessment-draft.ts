const SHORT: Record<PerspectiveId, string> = { T1: "새로움", T2: "대비", T3: "감정 크기", T4: "주변 반응", T5: "꾸준함", C1: "방향", C2: "조절", C3: "맞춤", C4: "의미", R1: "확인", R2: "혼자 시간", R3: "말 꺼내는 속도", R4: "표현" };
