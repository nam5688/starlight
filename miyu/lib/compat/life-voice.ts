/** 엔진이 이미 계산한 재료(parts · levels.dayElement)에서 읽힌 신호를 전부 모은다(자르지 않는다) */
export function allSceneSignalsOf(parts: Pick<CompatPart, "id" | "points" | "reason">[], dayElement: "same" | "generate" | "control"): SceneSignal[] {
  const part = (id: string) => parts.find((p) => p.id === id);
  const stem = part("day-stem");
  const out: SceneSignal[] = [stem && stem.points >= 10 ? "stem-combine" : dayElement === "same" ? "stem-same" : dayElement === "generate" ? "stem-generate" : "stem-control"];
  const branch = part("day-branch");
  if (branch) {
    if (/육합|반합|같은 글자/.test(branch.reason)) out.push("branch-pull");
    if (/충|형/.test(branch.reason)) out.push("branch-clash");
  }
  if (part("cross-pull")) out.push("cross-pull");
  if (part("cross-clash")) out.push("cross-clash");
  if (part("element-fill")) out.push("fill");
  if (part("element-overlap")) out.push("overlap");
  return out;
}

/**
 * 화면에 보일 신호 — 잘 맞는 쪽에서 둘, 차이가 나타나는 쪽에서 둘을 따로 고른다. 한쪽 신호가 많아도 다른 쪽 신호가 잘려 나가지 않아서
 * 합이 여럿인 두 사람에게 부딪히는 신호가, 충이 여럿인 두 사람에게 맞는 신호가 가려지지 않는다(예전에는 일간 사이 하나 + 나머지 둘로 잘라 긍정 후보가 앞서면 마찰 신호가 빠졌다).
 */
export function sceneSignalsOf(parts: Pick<CompatPart, "id" | "points" | "reason">[], dayElement: "same" | "generate" | "control"): SceneSignal[] {
  const all = allSceneSignalsOf(parts, dayElement);
  const take = (order: SceneSignal[]) => order.filter((s) => all.includes(s)).slice(0, SCENES_PER_SIDE);
  return [...take(GOOD_ORDER), ...take(CARE_ORDER)];
}

