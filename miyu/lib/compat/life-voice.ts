/** 읽힌 신호를 사이에 맞는 장면으로 — good은 잘 맞는 모습, care는 차이가 나타나는 상황 */
export function scenesOf(rel: CompatRelationship, signals: SceneSignal[]): { good: string[]; care: string[] } {
  const out = { good: [] as string[], care: [] as string[] };
  for (const s of signals) out[SCENE_VALENCE[s]].push(SCENES[rel][s]);
  return out;
}

