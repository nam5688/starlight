export type CoupleAnswer = OptionId | "x" | "y" | undefined;
export type CoupleAnswers = Partial<Record<string, CoupleAnswer>>;

/** 고른 답 하나 — 거의 없었어요(x) · 맞는 선택지 없음(y) · 미응답은 undefined(성향으로 읽지 않는다) */
export function coupleOption(sceneId: string, answer: CoupleAnswer): CoupleOption | undefined {
  if (answer === undefined || answer === "x" || answer === "y") return undefined;
  return COUPLE_SCENE_BY_ID[sceneId]?.options.find((o) => o.id === answer);
}
