/**
 * 한 선택지.
 * plain: 고른 답의 사실(이유를 추정하지 않는다) · shows: 이 답이 **그 장면에서** 보여 주는 방식(다른 장면과의 관계 · 이유는 말하지 않는다) ·
 * readThisAs: 이 답을 조건형으로 읽는 한 줄("~일 수 있어요" — 속마음을 사실로 말하지 않는다) ·
 * partnerCanTry: 상대가 해 볼 수 있는 것 — give 장면이면 "이렇게 건넨 마음을 알아봐 주는 법", need 장면이면 "이 방식으로 마음을 건네는 법", same 장면이면 "이 방식인 사람과 지낼 때 해 볼 것" ·
 * sayToThem: 상대가 건넬 수 있는 짧은 말 한 문장.
 */
export type CoupleOption = { id: OptionId; text: string; tag: string; plain: string; shows: string; readThisAs: string; partnerCanTry: string; sayToThem: string };

export type CoupleScene = {
  id: string;
  thread: CoupleThreadId;
  role: CoupleSceneRole;
  label: string;
  ask: string;
  options: [CoupleOption, CoupleOption, CoupleOption, CoupleOption];
  /** 이 장면이 가르려는 차이 */
  difference: string;
  /** 시범 인터뷰에서 확인할 것 */
  watch: string;
};

export type CoupleThread = {
  id: CoupleThreadId;
  /** 운영자가 말한 영역 이름 */
  area: string;
  name: string;
  kind: "cross" | "same";
  /** cross: [건네는 장면(give), 받는 장면(need)] · same: 두 장면 모두 내 반응 */
  scenes: [string, string];
  asks: string;
  /** 붙이면 안 되는 결론 */
  notThis: string[];
  /** 두 사람의 방식이 닿을 때 · 같을 때의 한 줄(조건형) */
  matchNote: string;
  /** 두 사람의 방식이 엇갈릴 때 · 다를 때의 한 줄(조건형, 속마음을 단정하지 않는다) */
  gapNote: string;
  /** 둘이 같이 해 볼 구체적인 행동 하나 */
  together: string;
  overlap: string;
};

