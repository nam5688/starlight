// 미유 "생활 행동" 질문 — 독립 설계 초안 0.1 (운영자 요청 2026-10-15, 검토 전, 화면 · 저장 · 리포트에 연결하지 않음)
//
// 왜 새로 설계했나
//  - 지금 화면의 22문항(개발용 예시)과 앞선 초안(situational-draft · deep-design)은 문장은 직접 썼지만 방향을 나눈 틀이 기존 이론의 틀과 닮았다(docs/assessment-source-audit.md).
//    "자체 개발"이라는 이름이나 문구 바꾸기로는 해결되지 않으므로, 이론의 틀이 아니라 **미유가 알아보려는 일상 행동**에서 영역을 새로 정했다.
//  - 영역은 이론 용어가 아니라 "계획이 바뀔 때 · 시작하는 방식 · 갈등에서 의견을 말할 때" 같은 생활 장면의 이름이다.
//
// 이 설계가 다른 점 (앞선 초안과 섞지 않는다)
//  - 문항 형식: "나는 ~한 편이다"(성향 진술)나 "장면 + 선택지 4개"가 아니라 **지난 한두 달 동안 실제로 한 행동의 빈도**(거의 없었어요 · 가끔 · 자주 · 거의 매번 + 그런 일이 없었어요)를 묻는다.
//  - 영역: 행동이 일어나는 장면에서 정했다(12개). 기질 · 성격 · 가까운 관계로 먼저 나누지 않고, 영역을 합친 점수 · 유형 이름도 만들지 않는다.
//  - 채점: 영역마다 두 행동 방식(A · B)을 정하고, 문항마다 "자주"가 어느 쪽인지(agree)와 이유(note)를 적는다. 영역 안에서 A · B 방향이 섞이게 해 아무 문항에나 "자주"를 고르는 습관이 점수로 남지 않게 했다.
//  - 읽는 규칙: 3문항에 모두 답했을 때만 읽고(해당 없음이 하나라도 있으면 판단 보류), 가운데에서 20 이상 벗어나면 뚜렷한 방향, 아니면 "뚜렷하지 않음". "약간 ~한 편"으로 나누지 않는다.
//
// 솔직한 한계
//  - 일상의 행동 주제는 연구가 오래 다뤄 온 것과 겹칠 수밖에 없다(영역별로 아래 `overlap`에 적었다). 겹치지 않는다고 주장하지 않으며, 기준은 **문항 문장 · 선택지 형식 · 채점표를 가져오지 않았다**는 것뿐이다.
//  - 공식 검사의 문항 원문과 대조하지는 못했다(원문 · 이용 허락 문서가 없다). 그래서 닮은 문장이 없다고 보증하지 않으며 검사 저작권 전문가의 검토가 필요하다.
//  - 이것은 장면을 고른 이유와 채점 방향의 기록일 뿐 실제 신뢰도 · 타당도가 아니다. 지난 한두 달 기억에 의존하는 방식이라 기억의 쏠림이 있을 수 있다. 시범 인터뷰 · 시범 응답 전에는 화면에 연결하지 않는다.
//  - 초안은 AI 도구(Claude)의 도움으로 정리했고 운영자가 아직 확인하지 않았다.

