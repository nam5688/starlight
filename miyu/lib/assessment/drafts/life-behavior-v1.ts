/** 응답 — 지난 한두 달의 빈도. "그런 일이 없었어요"는 점수에서 제외한다 */
export const LIFE_OPTIONS = [
  { value: 1, text: "거의 없었어요" },
  { value: 2, text: "가끔 있었어요" },
  { value: 3, text: "자주 있었어요" },
  { value: 4, text: "거의 매번 그랬어요" },
] as const;
export const LIFE_NONE_TEXT = "그런 일이 없었어요";
export const LIFE_PROMPT = "지난 한두 달 동안, 실제로 어땠나요?";

export const LIFE_ITEMS_PER_AREA = 3;
/** 영역의 가운데에서 이만큼 벗어나야 뚜렷한 방향으로 읽는다 (0~100, A 방식 쪽이 높다) */
export const LIFE_CLEAR_DISTANCE = 20;
export const LIFE_HOLD_TEXT = "답한 문항이 모자라 판단을 보류해요";
export const LIFE_UNCLEAR_TEXT = "현재 응답만으로는 뚜렷하지 않아요";

export type LifeValue = 1 | 2 | 3 | 4 | null;

/** 문항 하나의 응답을 영역의 A 방식 쪽 위치(0~100)로 옮긴다 — "자주"가 B 방향인 문항은 뒤집는다. 해당 없음이면 null */
export function itemPosition(it: LifeItem, value: LifeValue): number | null {
  if (value === null) return null;
  const frequency = ((value - 1) / 3) * 100; // 0(거의 없었어요) ~ 100(거의 매번)
  return it.agree === "a" ? frequency : 100 - frequency;
}

export type AreaReading =
  | { area: LifeAreaId; kind: "hold"; answered: number; text: string }
  | { area: LifeAreaId; kind: "unclear"; answered: number; position: number; text: string }
  | { area: LifeAreaId; kind: "clear"; answered: number; position: number; pole: Pole; text: string };

/** 영역별 읽기 — 영역끼리 합치지 않고, 하나의 점수나 유형 이름을 만들지 않는다 */
export function readLifeAreas(answers: Record<string, LifeValue>): AreaReading[] {
  return LIFE_AREAS.map((area): AreaReading => {
    const items = LIFE_ITEMS.filter((i) => i.area === area.id);
    const positions = items.map((i) => itemPosition(i, answers[i.id] ?? null)).filter((p): p is number => p !== null);
    if (positions.length < LIFE_ITEMS_PER_AREA) return { area: area.id, kind: "hold", answered: positions.length, text: LIFE_HOLD_TEXT };
    const position = Math.round(positions.reduce((s, p) => s + p, 0) / positions.length);
    if (Math.abs(position - 50) < LIFE_CLEAR_DISTANCE) return { area: area.id, kind: "unclear", answered: positions.length, position, text: LIFE_UNCLEAR_TEXT };
    const pole: Pole = position > 50 ? "a" : "b";
    return { area: area.id, kind: "clear", answered: positions.length, position, pole, text: pole === "a" ? area.a : area.b };
  });
}

/** 같은 영역 문항이 붙어 나오지 않게 영역을 돌려 가며 놓은 순서(화면에 연결할 때 쓴다) */
export function lifeItemsInOrder(): LifeItem[] {
  const out: LifeItem[] = [];
  for (let n = 1; n <= LIFE_ITEMS_PER_AREA; n++) for (const area of LIFE_AREAS) out.push(LIFE_ITEMS.find((i) => i.id === `${area.id}-${n}`)!);
  return out;
}

/** 채점 방향을 문항 정의에서 만든 글 — 문서 · 공개 기록이 정의와 어긋나지 않게 한다 */
export function lifeScoringText(it: LifeItem): string {
  const area = LIFE_AREAS.find((a) => a.id === it.area)!;
  const agree = it.agree === "a" ? area.a : area.b;
  const other = it.agree === "a" ? area.b : area.a;
  return `"자주 · 거의 매번"일수록 '${agree}' 쪽, "거의 없었어요"일수록 '${other}' 쪽으로 읽어요.`;
}
