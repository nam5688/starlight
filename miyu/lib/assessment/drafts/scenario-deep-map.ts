export const DEEP_MAP_SUMMARY = (() => {
  const replaced = DEEP_MAP.filter((r) => r.relation === "대체");
  const kept = DEEP_MAP.filter((r) => r.relation === "유지");
  const subCount = (rows: DeepMapRow[]) => rows.reduce<Record<string, number>>((m, r) => ({ ...m, [r.sub]: (m[r.sub] ?? 0) + 1 }), {});
  const keptBySub = subCount(kept);
  const replacedBySub = subCount(replaced);
  // 세부 항목마다 남는 문항 수 — 3개 미만이면 심화 규칙(서로 다른 문항 3개 이상일 때만 뚜렷한 방향을 읽는다)으로는 판단을 보류하게 된다
  const remaining = Object.keys({ ...keptBySub, ...replacedBySub }).map((sub) => ({ sub, kept: keptBySub[sub] ?? 0, replaced: replacedBySub[sub] ?? 0 }));
  return { total: DEEP_MAP.length, replaced: replaced.length, kept: kept.length, remaining };
})();
