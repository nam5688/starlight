const ORDER: Group[] = ["비겁", "식상", "재성", "관성", "인성"];

/** 천간 · 지지의 그룹 → 쉬운 설명. 같은 그룹이면 그 그룹 하나, 다르면 두 그룹이 함께 읽힌 설명 (순서 무관) */
export function periodPlain(stemGroup: Group, branchGroup: Group): PeriodPlain {
  if (stemGroup === branchGroup) return SINGLE[stemGroup];
  const [a, b] = [stemGroup, branchGroup].sort((x, y) => ORDER.indexOf(x) - ORDER.indexOf(y));
  return PAIR[`${a}+${b}`];
}

/** 연 단위(세운)로 쓸 때의 제목 — "~시기" → "~해" */
export const yearTitle = (p: PeriodPlain) => p.title.replace(/시기$/, "해");

/** 10년 단위 시기의 기간 줄 — 예: "2024.08–2034.07 · 사주에서 보는 10년 시기" */
export function periodLine(from: string, to: string): string {
  const dot = (s: string) => s.replace("-", ".");
  return `${dot(from)}–${dot(to)} · 사주에서 보는 10년 시기`;
}

