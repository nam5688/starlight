import type { FreeSummary } from "./types.ts";

export const SITUATION_PLAN = [
  { id: "work", title: "일하고 공부할 때" },
  { id: "close", title: "가까운 사람과 지낼 때" },
  { id: "decision", title: "새로운 선택 앞에서" },
  { id: "money", title: "돈을 쓰고 모을 때" },
  { id: "conflict", title: "갈등이나 스트레스가 올 때" },
] as const;

export type SituationId = (typeof SITUATION_PLAN)[number]["id"];

export type Situation = {
  id: SituationId;
  title: string;
  /** 무료 미리보기에 보이는 짧은 라벨 */
  strengthLabel: string;
  cautionLabel: string;
  /** 공감되는 장면 */
  scenario: string;
  strength: string;
  caution: string;
  /** 바로 해볼 한 가지 */
  tip: string;
};

type Variant = Omit<Situation, "id" | "title">;
const v = (strengthLabel: string, cautionLabel: string, scenario: string, strength: string, caution: string, tip: string): Variant => ({
  strengthLabel,
  cautionLabel,
  scenario,
  strength,
  caution,
  tip,
});

type Scores = { novelty: number; caution: number; sensitivity: number; persistence: number; anxiety: number; avoidance: number };
const HI = 60;
const LO = 40;

function scoresOf(summary: Pick<FreeSummary, "temperament" | "relationship">): Scores {
  const t = Object.fromEntries(summary.temperament.map((r) => [r.id, r.score]));
  const r = Object.fromEntries(summary.relationship.map((row) => [row.id, row.score]));
  return { novelty: t.novelty ?? 50, caution: t.caution ?? 50, sensitivity: t.sensitivity ?? 50, persistence: t.persistence ?? 50, anxiety: r.anxiety ?? 50, avoidance: r.avoidance ?? 50 };
}

