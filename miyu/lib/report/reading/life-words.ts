const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** "없음 · 적음 · 부족"과 이어서 알아볼 생활 말 어구(번역표의 stems) + "물의 기운"처럼 오행을 한글 이름으로 말하는 꼴 */
export const LIFE_POWER_SOURCE: string = [...LIFE_WORDS7.flatMap((w) => w.stems ?? []).map(escapeRe), "(?:나무|불|흙|쇠|물)의 기운"].join("|");

